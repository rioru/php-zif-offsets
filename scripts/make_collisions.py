#!/usr/bin/env python3
"""Generate COLLISIONS.md from the rows in data/.

The research tooling uses zval_ptr_dtor mod 0x1000 (the low 12 bits of
the ELF st_value, which survive ASLR in a leaked pointer) as a build
fingerprint. This script groups every row by each fingerprint field
and flags every colliding pair, so the fingerprint's discriminating
power is explicit instead of assumed.

Two severities are distinguished:
- identical: the full st_value matches too, so the two builds are
  interchangeable for that symbol (same offset, same layout).
- mod-only: just the low 12 bits match; the full offsets differ, so
  any other known offset still tells the builds apart.

Rows with a null fingerprint (the binary does not contain the symbol,
e.g. the Alpine session.so shared-extension rows) are excluded from the
analysis and listed explicitly.

Usage: make_collisions.py [--out COLLISIONS.md]
"""

import argparse
import json
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent

# fingerprint field -> underlying exploit offset field
FIELDS = [
    ("zval_ptr_dtor_mod_0x1000", "zval_ptr_dtor"),
    ("zif_system_mod_0x1000", "zif_system"),
]


def row_id(path):
    return path.stem


def load_rows():
    rows = []
    for path in sorted((REPO / "data").glob("*.json")):
        with open(path) as f:
            rows.append((path, json.load(f)))
    return rows


def exclusion_reason(row):
    if row["meta"]["binary_type"] == "shared-ext":
        return (
            "shared extension module: the symbol is an UND import here; "
            "core symbols live in the matching core-binary row (see meta.notes)"
        )
    return "symbol not present in this binary (see meta.notes)"


def field_section(field, offset_field, rows):
    """Return (markdown section, list of colliding pairs)."""
    fingerprinted = [
        (rid, row) for rid, row in rows if row["fingerprint"][field] is not None
    ]
    # Collisions are per architecture: an offset is only usable against a
    # target of the same ELF machine, so rows of different arches never
    # form a pair even when their low 12 bits coincide.
    groups = {}
    for rid, row in fingerprinted:
        arch = row["meta"].get("arch", "x86_64")
        groups.setdefault((arch, row["fingerprint"][field]), []).append((rid, row))

    pairs = []
    for key in sorted(groups):
        members = sorted(groups[key])
        for i in range(len(members)):
            for j in range(i + 1, len(members)):
                (rid_a, row_a), (rid_b, row_b) = members[i], members[j]
                off_a = row_a["exploit"][offset_field]
                off_b = row_b["exploit"][offset_field]
                pairs.append(
                    {
                        "mod": key[1],
                        "a": (rid_a, row_a),
                        "b": (rid_b, row_b),
                        "off_a": off_a,
                        "off_b": off_b,
                        "identical": off_a == off_b,
                    }
                )

    lines = [f"## {field.replace('_mod_0x1000', ' mod 0x1000')}", ""]
    if not pairs:
        lines += [
            f"No collisions among {len(fingerprinted)} fingerprinted rows "
            f"({len(groups)} distinct arch/value groups).",
            "",
        ]
        return "\n".join(lines), pairs

    lines += [
        f"{len(pairs)} colliding pair(s) among {len(fingerprinted)} "
        f"fingerprinted rows ({len(groups)} distinct arch/value groups).",
        "",
        f"| mod 0x1000 | row A | row B | {offset_field} A | {offset_field} B | verdict |",
        "|---|---|---|---|---|---|",
    ]
    for p in pairs:
        verdict = "identical" if p["identical"] else "mod-only"
        lines.append(
            f"| {p['mod']} | {p['a'][0]} | {p['b'][0]} | {p['off_a']} "
            f"| {p['off_b']} | {verdict} |"
        )
    lines.append("")
    return "\n".join(lines), pairs


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", default="COLLISIONS.md")
    args = ap.parse_args()

    rows = [(row_id(path), row) for path, row in load_rows()]

    sections = []
    all_pairs = {}
    excluded = [(rid, row) for rid, row in rows
                if row["fingerprint"][FIELDS[0][0]] is None
                or row["fingerprint"][FIELDS[1][0]] is None]
    for field, offset_field in FIELDS:
        section, pairs = field_section(field, offset_field, rows)
        sections.append(section)
        all_pairs[field] = pairs

    out = [
        "# COLLISIONS.md - build-fingerprint collisions",
        "",
        f"Generated by `scripts/make_collisions.py` from the rows in `data/` "
        f"({len(rows)} rows).",
        "",
        "The research tooling uses `zval_ptr_dtor mod 0x1000` - the low 12 bits "
        "of the ELF st_value, the bits that survive ASLR in a leaked pointer - "
        "as a build fingerprint. A collision means the fingerprint alone "
        "cannot tell the two builds apart. Pairs only form within one "
        "architecture (`meta.arch`): an offset is usable only against a "
        "target of the same ELF machine, so x86_64 and aarch64 rows never "
        "pair even when their low 12 bits coincide. Verdicts:",
        "",
        "- **identical** - the full st_value matches too: the two builds are "
        "interchangeable for that symbol (same offset, same layout).",
        "- **mod-only** - only the low 12 bits match; the full offsets differ, "
        "so any other known offset still distinguishes the builds.",
        "",
    ]

    if excluded:
        out += [
            "## Excluded rows",
            "",
            f"{len(excluded)} row(s) have a null fingerprint and are excluded "
            "from the analysis:",
            "",
            "| row | binary | reason |",
            "|---|---|---|",
        ]
        for rid, row in excluded:
            out.append(
                f"| {rid} | `{row['meta']['binary_path']}` "
                f"| {exclusion_reason(row)} |"
            )
        out.append("")

    out.append(sections[0])
    out.append(sections[1])

    # Auto-generated notes: pairs whose full offsets match.
    zval_pairs = all_pairs[FIELDS[0][0]]
    identical_zval = [p for p in zval_pairs if p["identical"]]
    both = [
        p for p in zval_pairs
        if p["identical"] and p["a"][1]["exploit"]["zif_system"]
        == p["b"][1]["exploit"]["zif_system"]
    ]
    out += ["## Notes", ""]
    if both:
        out += [
            "Builds that are fully interchangeable for the fingerprint pair "
            "(identical `zval_ptr_dtor` AND `zif_system`):",
            "",
        ]
        for p in both:
            out.append(
                f"- {p['a'][0]} ({p['a'][1]['meta']['package']}) == "
                f"{p['b'][0]} ({p['b'][1]['meta']['package']}) "
                f"({p['off_a']} / {p['a'][1]['exploit']['zif_system']})"
            )
        out.append("")
    if len(identical_zval) > len(both):
        out += [
            "Pairs with an identical `zval_ptr_dtor` offset but a differing "
            "`zif_system` (the primary fingerprint alone would pick the wrong "
            "zif_system target):",
            "",
        ]
        for p in identical_zval:
            if p in both:
                continue
            out.append(
                f"- {p['a'][0]} ({p['off_a']}, zif_system "
                f"{p['a'][1]['exploit']['zif_system']}) vs {p['b'][0]} "
                f"({p['off_b']}, zif_system {p['b'][1]['exploit']['zif_system']})"
            )
        out.append("")
    if not identical_zval:
        out += [
            "No two rows in this dataset share a full `zval_ptr_dtor` offset; "
            "every collision above is mod-only.",
            "",
        ]

    text = "\n".join(out).rstrip() + "\n"
    path = REPO / args.out
    path.write_text(text)
    print(f"wrote {path} ({len(rows)} rows, "
          f"{len(all_pairs[FIELDS[0][0]])} zval_ptr_dtor + "
          f"{len(all_pairs[FIELDS[1][0]])} zif_system colliding pairs)")


if __name__ == "__main__":
    main()
